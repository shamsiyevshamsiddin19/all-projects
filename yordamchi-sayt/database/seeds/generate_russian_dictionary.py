def translate_word(w):
    w_clean = w.strip().lower()
    if w_clean in RUSSIAN_1000_DICT:
        return RUSSIAN_1000_DICT[w_clean]
    # Fallback translations for variations
    return RUSSIAN_1000_DICT.get(w_clean, w_clean)

def main():
    with open('/home/shamsiddin/.gemini/antigravity-ide/brain/8f4698bc-555f-45f9-8bf3-c19798d753ad/scratch/russian_1000_words.json', 'r', encoding='utf-8') as f:
        data = json.load(f)

    # 1. Clean previous Russian words from dictionary_words
    from app import db
    from sqlalchemy import text

    print("Tozalash: dictionary_words dagi eski ruscha so'zlar o'chirilmoqda...")
    db.execute("DELETE FROM dictionary_words WHERE lang = 'russian'")

    order_list = []
    total_inserted = 0

    # Ranks: 1-100, 101-200, ..., 901-1000
    rank_keys = ['1-100', '101-200', '201-300', '301-400', '401-500', '501-600', '601-700', '701-800', '801-900', '901-1000']

    for idx, rk in enumerate(rank_keys):
        words = data.get(rk, [])
        cat_name = f"1-1000/{rk}"
        order_list.append(cat_name)
        print(f"Kategoriya: [{cat_name}] ({len(words)} ta so'z)...")

        for s_idx, ru_w in enumerate(words):
            uz_w = translate_word(ru_w)
            sort_order = idx * 100 + s_idx + 1

            db.execute(
                """INSERT INTO dictionary_words (lang, category, word_ru, word_uz, sort_order) 
                   VALUES (:l, :c, :ru, :uz, :so)""",
                {"l": "russian", "c": cat_name, "ru": ru_w, "uz": uz_w, "so": sort_order}
            )
            total_inserted += 1

    # Save category order
    db.storage_set(
        "dict_category_order_russian",
        json.dumps(order_list, ensure_ascii=False),
        {"owner_type": "global", "owner_key": "shared"}
    )

    print(f"\nMukammal yakunlandi! Jami {total_inserted} ta ruscha so'z to'g'ri o'zbekcha tarjimalari bilan bazaga yuklandi!")
    print(f"Kategoriyalar tartibi saqlandi: {order_list}")

if __name__ == '__main__':
    main()
